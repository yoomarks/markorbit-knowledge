export type IntakeMessageKey = keyof typeof zhCN;

export function intakeT(
  locale: AdminLocale,
  key: IntakeMessageKey,
  params?: IntakeMessageParams,
): string {
  const message = (locale === "en-US" ? enUS : zhCN)[key];
  if (!params) return message;
  return message.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name: string) => {
    const value = params[name];
    return value === undefined ? match : String(value);
  });
}
